from fastapi import FastAPI, UploadFile, File, Form, HTTPException
from fastapi.responses import JSONResponse
import uuid
import os
import json
from src.config.logging import logger
from src.utils.resumeLLMHandler import ResumeLLMHandler
from src.models.models import TailoredResume


app = FastAPI(title="ATS Resume Builder API", version="0.1")


# ------------------------------
# In-Memory Storage & Setup
# ------------------------------
SESSION_STORE = {}
os.makedirs("sessions", exist_ok=True)

# ------------------------------
# Endpoints
# ------------------------------

@app.get("/")
async def root():
    return {"message": "Welcome to the ATS Resume Builder API"}


@app.post("/resume", response_model=TailoredResume)
async def build_tailored_resume(file: UploadFile = File(...), job_description: str = Form(None)):
    """
    Upload a resume file (PDF/DOCX) along with Job description (optional).
    Extracts text, parses it, and returns the tailored resume JSON.
    """
    temp_pdf_path = None
    try:
        session_id = str(uuid.uuid4())
        temp_pdf_path = f"temp_{session_id}.pdf"
        
        with open(temp_pdf_path, "wb") as f:
            f.write(await file.read())
            
        handler = ResumeLLMHandler()
        
        if job_description:
            result_json_str = await handler.enhanced_resume_json(temp_pdf_path, job_description)
        else:
            result_json_str = await handler.basic_resume_json(temp_pdf_path)
            
        result_json = json.loads(result_json_str)

        # Cleanup temp file
        if os.path.exists(temp_pdf_path):
            os.remove(temp_pdf_path)
            
        # Also clean up the .md file generated by extractPdf.py if any
        temp_md_path = temp_pdf_path.replace(".pdf", ".md")
        if os.path.exists(temp_md_path):
            os.remove(temp_md_path)
            
        return result_json
        
    except Exception as e:
        logger.exception(f"Failed to build tailored resume: {str(e)}")
        if temp_pdf_path and os.path.exists(temp_pdf_path):
            os.remove(temp_pdf_path)
        raise HTTPException(status_code=500, detail=str(e))


if __name__=="__main__":
    import uvicorn
    uvicorn.run("main:app", port=8000, reload=True)