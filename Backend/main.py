@app.get("/")
async def root():
    return {"message": "Welcome to the ATS Resume Builder API"}


@app.post("/resume", response_model=TailoredResume)
async def build_tailored_resume(
    file: UploadFile = File(...), 
    job_description: str = Form(None),
    domain: str = Form("swe"),
    target_role: str = Form("Software Engineer")
):
    """
    Upload a resume file (PDF/DOCX) along with Job description (optional) and Target Role.
    Extracts text, parses it, and returns the tailored resume JSON.
    """
    temp_pdf_path = None
    try:
        session_id = str(uuid.uuid4())
        temp_pdf_path = f"temp_{session_id}.pdf"
        
        with open(temp_pdf_path, "wb") as f:
            f.write(await file.read())
            
        handler = ResumeLLMHandler()
        
        if job_description or domain != "swe":
            result_json_str = await handler.enhanced_resume_json(
                temp_pdf_path, 
                job_description or "", 
                domain=domain, 
                target_role=target_role
            )
        else:
            result_json_str = await handler.basic_resume_json(temp_pdf_path)
            
        result_json = json.loads(result_json_str)

        # Cleanup temp file
        if os.path.exists(temp_pdf_path):
            os.remove(temp_pdf_path)
            
        # Also clean up the .md file generated by extractPdf.py if any
        temp_md_path = temp_pdf_path.replace(".pdf", ".md")
        if os.path.exists(temp_md_path):
            os.remove(temp_md_path)
            
        return result_json
        
    except Exception as e:
        logger.exception(f"Failed to build tailored resume: {str(e)}")
        if temp_pdf_path and os.path.exists(temp_pdf_path):
            os.remove(temp_pdf_path)
        raise HTTPException(status_code=500, detail=str(e))


@app.post("/enhance")
async def enhance_resume_data(payload: dict = Body(...)):
    """
    Directly enhances an existing resume JSON data with a job description and target role.
    """
    try:
        resume_data = payload.get("resume_data")
        job_description = payload.get("job_description", "")
        domain = payload.get("domain", "swe")
        target_role = payload.get("target_role", "Software Engineer")
        
        if not resume_data:
            raise HTTPException(status_code=400, detail="Missing resume_data")
            
        handler = ResumeLLMHandler()
        enhanced_resume = await handler.enhance_resume(
            resume_data, 
            job_description, 
            domain=domain, 
            target_role=target_role
        )
        
        if enhanced_resume is None:
            raise HTTPException(status_code=500, detail="Failed to enhance resume with LLM")
            
        return enhanced_resume.model_dump()
    except Exception as e:
        logger.exception(f"Failed to enhance resume: {str(e)}")
        raise HTTPException(status_code=500, detail=str(e))


@app.post("/generate-pdf")
async def generate_pdf_endpoint(payload: dict = Body(...)):
    """
    Generates a PDF from resume JSON using the specified template.
    Template can be: 'resume_basic.html', 'resume_basic_2.html', or 'resume_basic_3.html'
    """
    try:
        resume_data = payload.get("resume_data")
        template_name = payload.get("template_name", "resume_basic_3.html")
        
        if not resume_data:
            raise HTTPException(status_code=400, detail="Missing resume_data")
            
        resume_obj = TailoredResume(**resume_data)
        generator = ResumePDFGenerator(resume_obj)
        generator.template_name = template_name
        
        pdf_id = str(uuid.uuid4())
        pdf_path = os.path.join("temp_folder", f"resume_{pdf_id}.pdf")
        generator.generate(pdf_path)
        
        return FileResponse(
            pdf_path,
            media_type="application/pdf",
            filename=f"Tailored_Resume.pdf"
        )
    except Exception as e:
        logger.exception(f"Failed to generate PDF: {str(e)}")
        raise HTTPException(status_code=500, detail=str(e))


